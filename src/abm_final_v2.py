# -*- coding: utf-8 -*-
"""
Deep-synthesis information-risk multi-agent simulation (final reproducible version)

Purpose
-------
Mechanism sensitivity analysis for the manuscript chapter on verifiable-relation
instability, risk evolution, risk-intelligence formation, and governance response.
The program does NOT estimate real-world causal effects or population incidence.

Agent roles
-----------
1. Synthetic-content generator / attacker
2. Platform exposure allocator
3. Heterogeneous audience agents
4. Verification / organizational-response agent
5. Governance-coordination agent

Main methodological upgrades
----------------------------
- Platform amplification enters exposure only, not user sharing twice.
- Real-world risk is generated by micro-level action transitions, not an arbitrary
  weighted harm index.
- Relation restoration is calculated from four relation-specific evidence states.
- Governance follows an evidence-confidence × potential-damage rule and includes
  reversible, time-limited provisional intervention.
- Population size is selected through a Monte Carlo convergence test.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from dataclasses import dataclass, asdict
from pathlib import Path
from typing import Dict, Iterable, List, Mapping, MutableMapping, Sequence, Tuple

import numpy as np


RELATIONS = ("source", "identity", "event", "propagation")
METRICS = ("exposure_rate", "misbelief_rate", "action_rate", "relation_restoration")


@dataclass(frozen=True)
class Coefficients:
    belief_intercept: float = -1.25
    belief_susceptibility: float = 1.25
    belief_bias: float = 1.15
    belief_unresolved: float = 1.25
    belief_literacy: float = 1.05

    share_intercept: float = -0.75
    share_susceptibility: float = 0.75
    share_bias: float = 0.80
    share_unresolved: float = 0.75
    share_literacy: float = 0.80

    action_intercept: float = -2.55
    action_susceptibility: float = 0.70
    action_bias: float = 0.75
    action_damage: float = 1.45
    action_unresolved: float = 0.90
    action_literacy: float = 0.75


@dataclass(frozen=True)
class ModelConfig:
    N: int = 4000
    T: int = 18
    seed_rate: float = 0.005
    lambda0: float = 2.25

    q_source: float = 0.65
    q_identity: float = 0.60
    q_event: float = 0.55
    q_propagation: float = 0.50
    kappa: float = 3.0
    coordination_evidence_gain: float = 0.50

    temp_strength: float = 0.25
    temp_window: int = 3
    evidence_threshold_low: float = 0.25
    evidence_threshold_high: float = 0.65
    damage_threshold: float = 0.60

    susceptibility_alpha: float = 2.2
    susceptibility_beta: float = 2.4
    literacy_alpha: float = 2.8
    literacy_beta: float = 2.2


@dataclass(frozen=True)
class CaseParam:
    event_id: str
    scene: str
    R_source: float
    R_identity: float
    R_event: float
    R_propagation: float
    platform_amp: float
    cognitive_bias: float
    verification_delay: int
    coordination: float
    max_intervention: float
    potential_damage: float

    @property
    def R(self) -> np.ndarray:
        return np.array(
            [self.R_source, self.R_identity, self.R_event, self.R_propagation],
            dtype=float,
        )


def sigmoid(x: np.ndarray | float) -> np.ndarray | float:
    x = np.asarray(x)
    # Stable logistic evaluation.
    out = np.empty_like(x, dtype=float)
    pos = x >= 0
    out[pos] = 1.0 / (1.0 + np.exp(-x[pos]))
    expx = np.exp(x[~pos])
    out[~pos] = expx / (1.0 + expx)
    return out if out.ndim else float(out)


def load_cases(path: str | Path) -> List[CaseParam]:
    rows: List[CaseParam] = []
    with Path(path).open("r", encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        required = {
            "event_id", "scene", "R_source", "R_identity", "R_event",
            "R_propagation", "platform_amp", "cognitive_bias",
            "verification_delay", "coordination", "max_intervention",
            "potential_damage",
        }
        missing = required - set(reader.fieldnames or [])
        if missing:
            raise ValueError(f"case calibration file missing columns: {sorted(missing)}")
        for r in reader:
            rows.append(
                CaseParam(
                    event_id=r["event_id"],
                    scene=r["scene"],
                    R_source=float(r["R_source"]),
                    R_identity=float(r["R_identity"]),
                    R_event=float(r["R_event"]),
                    R_propagation=float(r["R_propagation"]),
                    platform_amp=float(r["platform_amp"]),
                    cognitive_bias=float(r["cognitive_bias"]),
                    verification_delay=int(float(r["verification_delay"])),
                    coordination=float(r["coordination"]),
                    max_intervention=float(r["max_intervention"]),
                    potential_damage=float(r["potential_damage"]),
                )
            )
    if not rows:
        raise ValueError("no cases loaded")
    return rows


def evidence_state(
    t: int,
    R: np.ndarray,
    tau: int,
    q_base: np.ndarray,
    coordination: float,
    config: ModelConfig,
    evidence_multiplier: float,
) -> np.ndarray:
    q = (
        q_base
        * evidence_multiplier
        * (1.0 + config.coordination_evidence_gain * coordination)
    )
    tau_r = np.array([tau, tau, tau + 1, tau + 1], dtype=int)
    E = np.zeros(4, dtype=float)
    for j in range(4):
        if R[j] <= 0:
            E[j] = 1.0
        elif t >= tau_r[j] and q[j] > 0:
            E[j] = 1.0 - math.exp(-q[j] * (t - tau_r[j] + 1) / config.kappa)
        else:
            E[j] = 0.0
    return np.clip(E, 0.0, 1.0)


def unresolved_relation_instability(R: np.ndarray, E: np.ndarray) -> float:
    total = float(R.sum())
    if total <= 0:
        return 0.0
    return float(np.sum(R * (1.0 - E)) / total)


def governance_intensity(
    *,
    t: int,
    damage: float,
    evidence_confidence: float,
    coordination: float,
    max_intervention: float,
    config: ModelConfig,
    temporary_started_at: int | None,
) -> Tuple[float, int | None]:
    """Evidence × damage governance rule with a reversible temporary window."""
    c_factor = 0.7 + 0.3 * coordination

    if damage >= config.damage_threshold and evidence_confidence < config.evidence_threshold_low:
        if temporary_started_at is None and t >= 1:
            temporary_started_at = t
        if (
            temporary_started_at is not None
            and (t - temporary_started_at) < config.temp_window
        ):
            return config.temp_strength * c_factor, temporary_started_at
        # Temporary action expires when evidence has not crossed the threshold.
        return 0.0, temporary_started_at

    if evidence_confidence >= config.evidence_threshold_high:
        return min(0.95, max_intervention * c_factor), temporary_started_at

    if evidence_confidence >= config.evidence_threshold_low:
        return min(0.80, 0.55 * max_intervention * c_factor), temporary_started_at

    return 0.0, temporary_started_at


def simulate_once(
    case: CaseParam,
    *,
    seed: int,
    config: ModelConfig,
    coeff: Coefficients = Coefficients(),
    platform_multiplier: float = 1.0,
    bias_shift: float = 0.0,
    delay_shift: int = 0,
    evidence_multiplier: float = 1.0,
    coordination_shift: float = 0.0,
    intervention_multiplier: float = 1.0,
    temp_strength_override: float | None = None,
    lambda_multiplier: float = 1.0,
    no_governance: bool = False,
) -> Dict[str, float]:
    rng = np.random.default_rng(seed)

    R = case.R.copy()
    if R.sum() <= 0:
        R[:] = 1.0

    A = max(0.2, case.platform_amp * platform_multiplier)
    B = float(np.clip(case.cognitive_bias + bias_shift, 0.0, 1.0))
    tau = max(0, int(round(case.verification_delay + delay_shift)))
    C = float(np.clip(case.coordination + coordination_shift, 0.0, 1.0))
    D = float(np.clip(case.potential_damage, 0.0, 1.0))
    gmax = float(np.clip(case.max_intervention * intervention_multiplier, 0.0, 0.95))

    local_config = config
    if temp_strength_override is not None:
        local_config = ModelConfig(**{**asdict(config), "temp_strength": temp_strength_override})

    if no_governance:
        C = 0.0
        gmax = 0.0
        tau = 99
        evidence_multiplier = 0.0
        local_config = ModelConfig(**{**asdict(local_config), "temp_strength": 0.0})

    q_base = np.array(
        [config.q_source, config.q_identity, config.q_event, config.q_propagation],
        dtype=float,
    )

    n_seed = max(1, int(round(config.N * config.seed_rate)))
    exposed = n_seed
    believed_total = 0
    acted_total = 0

    # Initial micro-agents.
    S = rng.beta(config.susceptibility_alpha, config.susceptibility_beta, n_seed)
    L = rng.beta(config.literacy_alpha, config.literacy_beta, n_seed)
    E = np.zeros(4, dtype=float)
    U = unresolved_relation_instability(R, E)

    p_bel = sigmoid(
        coeff.belief_intercept
        + coeff.belief_susceptibility * S
        + coeff.belief_bias * B
        + coeff.belief_unresolved * U
        - coeff.belief_literacy * L
    )
    believed = rng.random(n_seed) < p_bel
    believed_total = int(believed.sum())

    if believed_total:
        Sb = S[believed]
        Lb = L[believed]
        p_act = sigmoid(
            coeff.action_intercept
            + coeff.action_susceptibility * Sb
            + coeff.action_bias * B
            + coeff.action_damage * D
            + coeff.action_unresolved * U
            - coeff.action_literacy * Lb
        )
        acted_total = int((rng.random(believed_total) < p_act).sum())
        p_share = sigmoid(
            coeff.share_intercept
            + coeff.share_susceptibility * Sb
            + coeff.share_bias * B
            + coeff.share_unresolved * U
            - coeff.share_literacy * Lb
        )
        active = int((rng.random(believed_total) < p_share).sum())
    else:
        active = 0

    temporary_started_at: int | None = None
    intervention_values: List[float] = []

    for t in range(config.T):
        E = evidence_state(
            t=t,
            R=R,
            tau=tau,
            q_base=q_base,
            coordination=C,
            config=local_config,
            evidence_multiplier=evidence_multiplier,
        )
        U = unresolved_relation_instability(R, E)
        evidence_confidence = 1.0 - U

        if no_governance:
            G = 0.0
        else:
            G, temporary_started_at = governance_intensity(
                t=t,
                damage=D,
                evidence_confidence=evidence_confidence,
                coordination=C,
                max_intervention=gmax,
                config=local_config,
                temporary_started_at=temporary_started_at,
            )
        intervention_values.append(G)

        if active <= 0 or exposed >= config.N:
            continue

        # Platform amplification affects reach only; it does not re-enter p_share.
        contact_mean = config.lambda0 * lambda_multiplier * A * (1.0 - G) * active
        n_contacts = min(config.N - exposed, int(rng.poisson(max(0.0, contact_mean))))
        if n_contacts <= 0:
            active = 0
            continue

        exposed += n_contacts
        S = rng.beta(config.susceptibility_alpha, config.susceptibility_beta, n_contacts)
        L = rng.beta(config.literacy_alpha, config.literacy_beta, n_contacts)

        p_bel = sigmoid(
            coeff.belief_intercept
            + coeff.belief_susceptibility * S
            + coeff.belief_bias * B
            + coeff.belief_unresolved * U
            - coeff.belief_literacy * L
        )
        believed = rng.random(n_contacts) < p_bel
        n_believed = int(believed.sum())
        believed_total += n_believed

        if n_believed:
            Sb = S[believed]
            Lb = L[believed]
            p_act = sigmoid(
                coeff.action_intercept
                + coeff.action_susceptibility * Sb
                + coeff.action_bias * B
                + coeff.action_damage * D
                + coeff.action_unresolved * U
                - coeff.action_literacy * Lb
            )
            acted_total += int((rng.random(n_believed) < p_act).sum())

            p_share = sigmoid(
                coeff.share_intercept
                + coeff.share_susceptibility * Sb
                + coeff.share_bias * B
                + coeff.share_unresolved * U
                - coeff.share_literacy * Lb
            )
            active = int((rng.random(n_believed) < p_share).sum())
        else:
            active = 0

    relation_restoration = 1.0 - unresolved_relation_instability(R, E)

    return {
        "exposure_rate": exposed / config.N,
        "misbelief_rate": believed_total / config.N,
        "action_rate": acted_total / config.N,
        "relation_restoration": relation_restoration,
        "mean_intervention": float(np.mean(intervention_values) if intervention_values else 0.0),
        "max_intervention": float(np.max(intervention_values) if intervention_values else 0.0),
    }


def design_stream(n_cases: int, reps: int, seed: int) -> Tuple[np.ndarray, np.ndarray]:
    rng = np.random.default_rng(seed)
    case_index = rng.integers(0, n_cases, size=reps)
    sim_seed = rng.integers(0, 2**31 - 1, size=reps)
    return case_index, sim_seed


def run_design(
    cases: Sequence[CaseParam],
    case_index: Sequence[int],
    sim_seed: Sequence[int],
    *,
    config: ModelConfig,
    coeff: Coefficients = Coefficients(),
    scenario: Mapping[str, float | int] | None = None,
    no_governance: bool = False,
) -> List[Dict[str, float]]:
    scenario = dict(scenario or {})
    out: List[Dict[str, float]] = []
    for ci, sd in zip(case_index, sim_seed):
        out.append(
            simulate_once(
                cases[int(ci)],
                seed=int(sd),
                config=config,
                coeff=coeff,
                no_governance=no_governance,
                **scenario,
            )
        )
    return out


def summarize_runs(rows: Sequence[Mapping[str, float]]) -> Dict[str, float]:
    arr = np.array([[r[m] for m in METRICS] for r in rows], dtype=float)
    result: Dict[str, float] = {}
    for j, m in enumerate(METRICS):
        result[f"{m}_mean"] = float(arr[:, j].mean())
        result[f"{m}_se"] = float(arr[:, j].std(ddof=1) / math.sqrt(len(arr)))
        result[f"{m}_q1"] = float(np.percentile(arr[:, j], 25))
        result[f"{m}_q3"] = float(np.percentile(arr[:, j], 75))
    return result


def write_rows(path: Path, rows: Sequence[Mapping[str, object]]) -> None:
    if not rows:
        raise ValueError(f"no rows for {path}")
    keys = list(rows[0].keys())
    with path.open("w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=keys)
        w.writeheader()
        w.writerows(rows)


def convergence_experiment(cases: Sequence[CaseParam], outdir: Path) -> Dict[int, Dict[str, float]]:
    N_grid = [1000, 2000, 4000, 8000, 16000]
    reps = 500
    case_index, sim_seed = design_stream(len(cases), reps, 20260830)
    summary: Dict[int, Dict[str, float]] = {}
    raw: List[Dict[str, object]] = []

    for N in N_grid:
        cfg = ModelConfig(N=N)
        runs = run_design(cases, case_index, sim_seed, config=cfg)
        s = summarize_runs(runs)
        summary[N] = s
        for rep, (ci, sd, r) in enumerate(zip(case_index, sim_seed, runs), start=1):
            raw.append({"N": N, "rep": rep, "event_id": cases[int(ci)].event_id, "seed": int(sd), **r})

    ref = summary[16000]
    out_rows = []
    for N in N_grid:
        s = summary[N]
        diffs = [abs(s[f"{m}_mean"] - ref[f"{m}_mean"]) for m in METRICS]
        out_rows.append({
            "N": N,
            "repetitions": reps,
            **{k: v for k, v in s.items() if k.endswith("_mean") or k.endswith("_se")},
            "max_abs_mean_difference_vs_N16000": max(diffs),
        })

    write_rows(outdir / "abm_convergence_summary.csv", out_rows)
    write_rows(outdir / "abm_convergence_raw.csv", raw)
    return summary


def scenario_experiment(cases: Sequence[CaseParam], outdir: Path) -> List[Dict[str, object]]:
    scenarios: Dict[str, Dict[str, float | int]] = {
        "基准": {},
        "平台放大": {"platform_multiplier": 1.25},
        "认知偏差增强": {"bias_shift": 0.15},
        "响应滞后": {"delay_shift": 3},
        "关系证据强化": {"evidence_multiplier": 1.45, "delay_shift": -2},
        "协同与可逆干预": {
            "coordination_shift": 0.30,
            "intervention_multiplier": 1.25,
            "temp_strength_override": 0.35,
            "delay_shift": -1,
        },
    }
    reps = 500
    config = ModelConfig(N=4000)
    case_index, sim_seed = design_stream(len(cases), reps, 20260831)
    summary_rows: List[Dict[str, object]] = []
    raw_rows: List[Dict[str, object]] = []

    for name, scenario in scenarios.items():
        gov = run_design(cases, case_index, sim_seed, config=config, scenario=scenario)
        no_gov = run_design(
            cases,
            case_index,
            sim_seed,
            config=config,
            scenario={
                "platform_multiplier": scenario.get("platform_multiplier", 1.0),
                "bias_shift": scenario.get("bias_shift", 0.0),
                "delay_shift": scenario.get("delay_shift", 0),
                "evidence_multiplier": scenario.get("evidence_multiplier", 1.0),
            },
            no_governance=True,
        )
        sg = summarize_runs(gov)
        sn = summarize_runs(no_gov)
        control = 1.0 - sg["action_rate_mean"] / max(sn["action_rate_mean"], 1e-12)
        summary_rows.append({
            "scenario": name,
            "repetitions": reps,
            **{k: v for k, v in sg.items() if k.endswith("_mean") or k.endswith("_se")},
            "action_rate_no_governance_mean": sn["action_rate_mean"],
            "relative_control_effect": control,
        })
        for rep, (ci, sd, rg, rn) in enumerate(zip(case_index, sim_seed, gov, no_gov), start=1):
            raw_rows.append({
                "scenario": name,
                "rep": rep,
                "event_id": cases[int(ci)].event_id,
                "seed": int(sd),
                **{f"gov_{k}": v for k, v in rg.items()},
                **{f"no_gov_{k}": v for k, v in rn.items()},
            })

    write_rows(outdir / "abm_scenario_summary.csv", summary_rows)
    write_rows(outdir / "abm_scenario_raw.csv", raw_rows)
    (outdir / "abm_scenarios.json").write_text(
        json.dumps(scenarios, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    return summary_rows


def delay_intervention_sensitivity(cases: Sequence[CaseParam], outdir: Path) -> List[Dict[str, object]]:
    delays = list(range(0, 7))
    multipliers = [0.6, 1.0, 1.4]
    reps = 400
    config = ModelConfig(N=4000)
    case_index, sim_seed = design_stream(len(cases), reps, 4242)
    summary_rows: List[Dict[str, object]] = []
    raw_rows: List[Dict[str, object]] = []

    for m in multipliers:
        for d in delays:
            runs = run_design(
                cases,
                case_index,
                sim_seed,
                config=config,
                scenario={"delay_shift": d, "intervention_multiplier": m},
            )
            s = summarize_runs(runs)
            summary_rows.append({
                "delay_shift": d,
                "intervention_multiplier": m,
                "repetitions": reps,
                **{k: v for k, v in s.items() if k.endswith("_mean") or k.endswith("_se")},
            })
            for rep, (ci, sd, r) in enumerate(zip(case_index, sim_seed, runs), start=1):
                raw_rows.append({
                    "delay_shift": d,
                    "intervention_multiplier": m,
                    "rep": rep,
                    "event_id": cases[int(ci)].event_id,
                    "seed": int(sd),
                    **r,
                })

    write_rows(outdir / "abm_delay_intervention_summary.csv", summary_rows)
    write_rows(outdir / "abm_delay_intervention_raw.csv", raw_rows)
    return summary_rows


def oat_robustness(cases: Sequence[CaseParam], outdir: Path) -> List[Dict[str, object]]:
    """One-at-a-time ±20% checks matching the archived robustness output."""
    reps = 300
    base_cfg = ModelConfig(N=4000)
    base_coeff = Coefficients()
    case_index, sim_seed = design_stream(len(cases), reps, 7319)

    tests = [
        ("平台接触率lambda0", 0.8), ("平台接触率lambda0", 1.2),
        ("证据质量q", 0.8), ("证据质量q", 1.2),
        ("临时干预强度", 0.8), ("临时干预强度", 1.2),
        ("行动截距", 0.8), ("行动截距", 1.2),
    ]

    baseline_runs = run_design(cases, case_index, sim_seed, config=base_cfg, coeff=base_coeff)
    baseline = summarize_runs(baseline_runs)
    out_rows: List[Dict[str, object]] = [{
        "parameter": "baseline", "multiplier": 1.0,
        **{k: v for k, v in baseline.items() if k.endswith("_mean")},
        "action_change_vs_baseline": 0.0,
    }]

    for param, mult in tests:
        coeff = base_coeff
        scenario: Dict[str, float | int] = {}
        if param == "平台接触率lambda0":
            scenario["lambda_multiplier"] = mult
        elif param == "证据质量q":
            scenario["evidence_multiplier"] = mult
        elif param == "临时干预强度":
            scenario["temp_strength_override"] = base_cfg.temp_strength * mult
        elif param == "行动截距":
            coeff = Coefficients(**{
                **asdict(base_coeff),
                "action_intercept": base_coeff.action_intercept * mult,
            })

        runs = run_design(
            cases, case_index, sim_seed,
            config=base_cfg, coeff=coeff, scenario=scenario
        )
        s = summarize_runs(runs)
        out_rows.append({
            "parameter": param,
            "multiplier": mult,
            **{k: v for k, v in s.items() if k.endswith("_mean")},
            "action_change_vs_baseline": s["action_rate_mean"] - baseline["action_rate_mean"],
        })

    write_rows(outdir / "abm_oat_robustness.csv", out_rows)
    return out_rows

def write_model_metadata(outdir: Path) -> None:
    metadata = {
        "model_config": asdict(ModelConfig()),
        "coefficients": asdict(Coefficients()),
        "output_definitions": {
            "exposure_rate": "fraction of user agents exposed at least once",
            "misbelief_rate": "fraction of user agents that accepted the false/synthetic claim",
            "action_rate": "fraction of user agents that generated a real-world risk action after belief",
            "relation_restoration": "1 - initial-instability-weighted unresolved relation share at T",
            "relative_control_effect": "1 - mean(action_rate_governance)/mean(action_rate_no_governance)",
        },
        "interpretation_boundary": (
            "Mechanism sensitivity analysis only. Case codes anchor relation patterns and ordinal "
            "parameter ranges; they do not estimate behavioral probabilities or real-world policy effects."
        ),
    }
    (outdir / "abm_model_metadata.json").write_text(
        json.dumps(metadata, ensure_ascii=False, indent=2), encoding="utf-8"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cases", required=True, help="case calibration CSV")
    parser.add_argument("--outdir", required=True, help="output directory")
    args = parser.parse_args()

    outdir = Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    cases = load_cases(args.cases)

